import { UsageError, sentence, parseBoolean, strings, LANGS } from './i18n.mjs';

// Which label a piece of content needs under Article 50(4) of the EU AI Act, read together with the
// Commission's Article 50 Guidelines (20 July 2026), the EU icon guidance and the Code of Practice on
// Transparency of AI-Generated Content (10 June 2026). It covers professional deployers: people and
// companies who use AI to make content in a professional activity. It is a checklist, not legal
// advice; the sources are in `SOURCES`.

export const SOURCES = {
  act: 'Regulation (EU) 2024/1689 (AI Act), Article 50(4) and 50(5), and the deep fake definition in Article 3(60)',
  guidelines:
    'Guidelines on transparency obligations for providers and deployers of AI systems (European Commission, 20 July 2026), https://digital-strategy.ec.europa.eu/en/library/guidelines-transparency-obligations-providers-and-deployers-ai-systems',
  icons: 'https://digital-strategy.ec.europa.eu/en/policies/eu-icons-labelling-ai-generated-content',
  code: 'https://digital-strategy.ec.europa.eu/en/policies/code-practice-ai-generated-content',
};

const DISCLAIMER =
  "A checklist based on the AI Act, the Commission's Article 50 Guidelines (20 July 2026) and the Code of Practice on Transparency of AI-Generated Content (10 June 2026), not legal advice.";

// The one question decide asks when a deciding fact is missing, keyed by the argument that answers
// it (`missing`): realistic is --realistic / --no-realistic on the CLI and realistic: true / false over MCP.
const QUESTIONS = {
  realistic: 'Would the people who will see it take it for a genuine photo, recording or event?',
  public_interest: 'Is the text published to inform the public on a matter of public interest?',
  editorial_review:
    'Did a person with relevant knowledge check the substance before publishing (at least fact-checked it), with no AI changes after sign-off, and does a named person or company hold editorial responsibility?',
};

const DEPLOYER_NOTE =
  'The duty falls on the deployer: the person or organisation that used the AI system in a professional activity. It binds deployers in the EU, and deployers elsewhere when they foresee the content being used in the EU, for example by publishing it on the open internet (Article 2(1); Guidelines para 13). ' +
  'A natural person acting in a purely personal, non-professional way has no deployer duty (Article 2(10); Guidelines paras 19-20); anything done for pay or regular economic benefit, as a freelancer, or for an employer is professional, and the duty then sits with that person or the company. ' +
  'Someone who only republishes content generated by others is not a deployer, though keeping the label is encouraged (Guidelines para 16).';

// The label sentence, or null in a language without built-in wording (the user writes it).
const disclosureOf = (label) => (LANGS[label.lang] ? sentence(label) : null);

const ORIGINS = ['generated', 'modified', 'assisted', 'human'];
const MEDIA = ['image', 'video', 'audio', 'text'];

export function decide(input = {}) {
  const { media, origin } = input;
  if (media == null || origin == null) throw new UsageError('decide needs --media and --origin');
  if (!MEDIA.includes(media)) throw new UsageError(`media must be one of: ${MEDIA.join(', ')}`);
  if (!ORIGINS.includes(origin)) throw new UsageError(`origin must be one of: ${ORIGINS.join(', ')}`);
  const realistic = parseBoolean(input.realistic, 'realistic');
  const creative = parseBoolean(input.creative, 'creative');
  const publicInterest = parseBoolean(input.publicInterest, 'public-interest');
  const editorialReview = parseBoolean(input.editorialReview, 'editorial-review');
  const lang = input.lang ?? 'en';
  strings(lang); // one of the 24 EU languages

  // A verdict needs the deciding fact; without it, ask instead of guessing. For public-interest
  // text that fact is the editorial review (Guidelines paras 133-138).
  if (origin === 'generated' || origin === 'modified') {
    let missing = null;
    if (media !== 'text') missing = realistic === undefined ? 'realistic' : null;
    else if (publicInterest === undefined) missing = 'public_interest';
    else if (publicInterest && editorialReview === undefined) missing = 'editorial_review';
    if (missing) {
      const label = { kind: origin, media: [media], lang };
      return {
        required: 'unknown',
        missing,
        question: QUESTIONS[missing],
        label,
        disclosure: disclosureOf(label),
        sources: SOURCES,
        disclaimer: DISCLAIMER,
      };
    }
  }

  const out = {
    required: false,
    verdict: '',
    basis: '',
    label: null,
    officialIcon: null,
    placement: [],
    accessibility: [],
    notes: [],
    sources: SOURCES,
    disclaimer: DISCLAIMER,
  };

  if (origin === 'human') {
    out.verdict = 'NOT REQUIRED: human-made content';
    out.basis = 'The AI Act does not regulate human-made content.';
    out.label = { kind: 'human', media: [media], lang };
    out.notes.push(
      'A "human-made" label is a claim to your audience. Use it only when no generative AI produced or changed this part. Standard edits such as spell-check or noise reduction do not defeat the claim; any generative change does.',
      'The human-made mark is this project\'s design: the same disc as the EU icon with a hand instead of "AI", so the two read as a pair. It is not an EU icon and has no meaning under the AI Act.',
      'Where you use the mark, explain it once (a legend, caption or an "about our labels" page), as the Code encourages for labels other than the EU icon (Measure 2.1). In business communication a false claim can be a misleading practice under the Unfair Commercial Practices Directive 2005/29/EC (Article 6), separate from the AI Act.'
    );
    return finish(out, media, lang);
  }

  if (origin === 'assisted') {
    out.verdict = 'NOT REQUIRED: standard edits only (on this reading)';
    out.basis =
      media === 'text'
        ? 'On this reading, text that AI only touched with standard edits (spelling, grammar, formatting) is not "generated or manipulated" by AI (Guidelines para 59 describes manipulation as alteration beyond standard editing), as long as the edit does not change its meaning, style or intent. Article 50(2) has an explicit exception of this kind for providers ("an assistive function for standard editing"; Guidelines para 90).'
        : 'On this reading, minor AI edits that do not change what the content shows (colour correction, noise reduction, lighting, removing a passer-by) normally do not make it a deep fake, but this depends on context; substantial edits to journalistic images do (Guidelines para 116). If the edit changes how a viewer judges what is real, treat it as "modified".';
    out.label = { kind: 'basic', media: [media], lang };
    out.notes.push('A label is optional here. If the edit changes what the content shows or says, treat it as "modified" instead.');
    return finish(out, media, lang);
  }

  const kind = origin; // generated | modified
  out.label = { kind, media: [media], lang };
  out.officialIcon = kind;
  out.notes.push(
    `Labels from render and stamp use the basic EU icon with this text, which the EU guidance allows. The official icon with the same meaning, in English only, is available unchanged: "eu ${kind}".`
  );

  if (media === 'text') {
    if (publicInterest && !editorialReview) {
      out.required = true;
      out.verdict = 'REQUIRED: AI text on a matter of public interest, without editorial review';
      out.basis =
        'Article 50(4), second subparagraph: AI-generated or AI-manipulated text published to inform the public on matters of public interest, without human review or editorial control (Guidelines paras 130-132).';
    } else if (publicInterest) {
      out.verdict = 'NOT REQUIRED: reviewed text with editorial responsibility';
      out.basis =
        'The text had substantive human review or editorial control and a natural or legal person holds editorial responsibility (Article 50(4), second subparagraph; Guidelines paras 133-138). Publish who holds editorial responsibility and how to contact them (legal information or colophon), and label the text anyway if AI changed it after sign-off.';
      out.notes.push('Labelling is still a good practice and builds trust.');
    } else {
      out.verdict = 'NOT REQUIRED: text not published on a matter of public interest';
      out.basis = 'The text is not published to inform the public on matters of public interest (Guidelines para 131). Labelling is a voluntary good practice.';
    }
    if (out.required) {
      out.placement.push('Put the label at the start of the text or right next to its headline, so readers see it before they read.');
      out.notes.push(DEPLOYER_NOTE);
    } else {
      out.placement.push('If you label it, place the label next to the headline or byline.');
    }
    return finish(out, media, lang);
  }

  if (realistic) {
    out.required = true;
    out.verdict = creative
      ? 'REQUIRED, lighter placement: evidently creative work (Article 50(4), Guidelines para 123)'
      : `REQUIRED: realistic ${kind === 'modified' ? 'AI-modified' : 'AI'} ${media}, a deep fake under Article 50(4)`;
    out.basis =
      'Article 50(4), first subparagraph: a deep fake, meaning AI-generated or AI-manipulated content that resembles existing persons, objects, places, entities or events and would falsely appear authentic (Article 3(60)). This includes realistic product, place and event images, not only people. ' +
      'The test is whether the foreseeable audience, including children and less AI-literate viewers, would take it as authentic, assessed objectively (Guidelines paras 113-115).';
    out.notes.push(DEPLOYER_NOTE);
    if (creative) {
      out.notes.push(
        'Evidently artistic, creative, satirical or fictional work (read strictly: content that is purely informative or commercial, such as news or a product shot, does not count, and an advertisement only in specific cases): the label need not be embedded, but it must still be clear, distinguishable and seen at first exposure without the viewer doing anything, for example next to the frame, in the description, or in the opening or end credits (Article 50(5); Guidelines paras 122-123; Code of Practice Commitment 3).'
      );
    }
  } else {
    out.verdict = 'NOT REQUIRED: not a deep fake (would not be taken for real)';
    out.basis =
      'The content would not be taken for a real person, object, place or event by its foreseeable audience (clearly stylised, impossible, or shown where nobody expects authenticity). Labelling is a voluntary good practice.';
  }

  const spoken = (LANGS[lang] ?? LANGS.en).spoken;
  const placement = {
    image: [
      'Burn the label into the image pixels (the `stamp` command), so it stays visible when the image is downloaded or reshared.',
      "Use a corner where platforms do not draw their own buttons or captions; the label must be visible at first sight, with nothing covering it. For social posts, crop to the platform's final aspect first (Instagram 4:5 or 1:1), then stamp with --display-width 390, so the label sits inside every crop and is readable full width on a phone.",
    ],
    video: [
      'Show the label from the first frame, repeat it at regular intervals where possible and at least after every break (such as an ad break), so people who join mid-way still see it (Code Sub-measure 1.2.2(b); Guidelines para 143). The Code also encourages keeping it on screen for the whole video or the whole AI part; this project recommends that, as the simplest way to cover every viewer.',
      'Burn it into the frames so it survives downloads and reshares; place it away from the player controls.',
      'If only some parts are AI (for example the voice in certain scenes), keep the label above and add per-segment icons on top of it, never instead of it.',
    ],
    audio: [
      `Audio-only content cannot show a visual label: add a short audible disclaimer at the start, in the language of the recording (for example "${spoken}"). In long or live recordings repeat it at regular intervals where appropriate, and at least after breaks (Code Sub-measure 1.2.3).`,
      'Where the audio has a player, cover art or a page, show the visual label there too.',
    ],
  };
  if (realistic && creative) {
    out.placement.push(
      'For an evidently creative work, place the label so it does not hamper the work but is still seen at first exposure: next to the frame, in the description, or in the opening or end credits.'
    );
    if (media === 'audio') out.placement.push(placement.audio[0]);
  } else {
    out.placement.push(...placement[media]);
  }
  return finish(out, media, lang);
}

// The command to run after decide: the MCP tool with the arguments to pass unchanged, the arguments
// still to fill in (MCP names), and the same step as a CLI line. `ai-labels` is the package's command
// (also installed as `ai-content-labels`); in a copied skill it is node <skill>/scripts/ai-labels.mjs.
export function nextStep(label, disclosure) {
  const own = disclosure == null; // no built-in wording: the user writes the label text
  const flags =
    `--kind ${label.kind} --media ${label.media.join(',')}` + (label.lang !== 'en' ? ` --lang ${label.lang}` : '') + (own ? ' --text "label in that language"' : '');
  const text = own ? ['text'] : [];
  switch (label.media[0]) {
    case 'image':
      return { tool: 'stamp_image', arguments: { ...label }, fill: ['input', 'description', ...text], cli: `ai-labels stamp <image> ${flags} --description "what it shows"` };
    case 'text':
      return { tool: 'render_label', arguments: { ...label, format: 'html' }, fill: text, cli: `ai-labels render --format html ${flags}`, note: 'at the top of the text' };
    case 'video':
      return {
        tool: 'render_label',
        arguments: { ...label },
        fill: ['out', 'height', ...text],
        cli: `ai-labels render ${flags} --out label.png --height <6% of the shorter side>`,
        note: 'then ffmpeg -i in.mp4 -i label.png -filter_complex "overlay=24:24" -c:a copy out.mp4',
      };
    default:
      return { tool: 'render_label', arguments: { ...label, format: 'html' }, fill: text, cli: `ai-labels render --format html ${flags}`, note: 'next to the player, and a short spoken disclaimer at the start' };
  }
}

function finish(out, media, lang) {
  const said = out.label && disclosureOf(out.label);
  // A placeholder, not a ready description, so nobody pastes an example onto an unrelated image.
  // It is built from the computed sentence, so a human-made verdict never shows an AI one.
  const example = said ? ` (alt="${LANGS[lang].describe} ${said}")` : ', both in the language of the page';
  const describe = {
    image: `Give the image an alt text that says what it shows, then the label sentence${example}; text burned into an image is invisible to screen readers.`,
    video:
      'Put the label sentence in visible text next to the player (title or description) and say it in the audio: a short spoken disclaimer at the start or a line in the audio description track (WCAG 1.2.5); captions alone do not reach blind viewers.',
    audio:
      'Put the label sentence in text next to the player or in its aria-label, and at the start of the transcript (WCAG 1.2.1), so people who cannot see the cover art still get it.',
    text: 'Make the label readable by screen readers: real text next to the headline (render --format html), or a label image whose alt text is the label sentence.',
  };
  out.accessibility.push(
    describe[media],
    'Keep the label large enough to read on the smallest screen where the content appears; ai-content-labels guarantees 4.5:1 text contrast on any backdrop.',
    media === 'video'
      ? 'Do not animate the label (WCAG 2.2.2) or make it flash (WCAG 2.3.1); a label that changes during a video must stay on screen long enough to be read.'
      : 'Do not animate the label (WCAG 2.2.2) or make it flash (WCAG 2.3.1).'
  );
  if (out.label) {
    out.disclosure = said;
    out.next = nextStep(out.label, said);
    if (said == null) {
      out.notes.push(
        `There is no built-in wording for "${lang}": write the label sentence in that language yourself and pass it as --text (and --human-text for a human-made part) when you render or stamp.`
      );
    }
  }
  return out;
}
